SETS = [SET_99, SET_54]


def _level_for(entries):
    if entries is None:
        return "중"
    n = len(entries)
    if n <= 2:
        return "하"
    if n == 3:
        return "중"
    return "상"


def _combo_str(combo):
    if combo is None:
        return "회계상 거래 아님"
    return f"{combo[0]} / {combo[1]}"


def build_entries():
    out = []
    for s in SETS:
        subject, round_label = s["subject"], s["round"]
        for item in s["items"]:
            out.append({
                "id": f"분개연습|{subject}|{round_label}|{item['no']}",
                "exam": "분개연습",
                "subject": subject,
                "level": _level_for(item["entries"]),
                "combo": _combo_str(item["combo"]),
                "combo_pair": list(item["combo"]) if item["combo"] else None,
                "type": "bunkae",
                "round": round_label,
                "num": item["no"],
                "stem": item["tx"],
                "entries": item["entries"],
                "interp": item["interp"],
                "answer": "correct",
            })
    return out


def main():
    parser = argparse.ArgumentParser(description="손수 작성한 분개 연습문제 -> questions.json 병합")
    parser.add_argument("--merge-into", required=True)
    args = parser.parse_args()

    new_entries = build_entries()

    with open(args.merge_into, encoding="utf-8") as f:
        existing = json.load(f)
    # 기존 자동추출(extract_bunkae.py) 분개연습 문제는 각주오염 등 품질 문제가 있어 전부 교체
    existing = [q for q in existing if q.get("exam") != "분개연습"]

    merged = existing + new_entries
    with open(args.merge_into, "w", encoding="utf-8") as f:
        json.dump(merged, f, ensure_ascii=False, indent=2)

    print(f"분개연습(손수 작성) {len(new_entries)}문항으로 교체 -> 총 {len(merged)}문제")


if __name__ == "__main__":
    main()
