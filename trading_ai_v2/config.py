    US_MIN_PRICE = 5.0

    # "성장주 TOP N" 전용 기준 (저평가 우량주 필터와는 별개 -- value_screener.select_growth_picks)
    # 전분기 대비 매출액 증가율이 이 값 이상이면 "성장 우수" 종목으로 별도 표에 노출
